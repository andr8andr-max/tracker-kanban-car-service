let lang = "ru";

export function setLang(l) {
  lang = l === "en" ? "en" : "ru";
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function t(key, params) {
  let s = (dict[lang] && dict[lang][key]) || dict.ru[key] || key;
  if (params) {
    for (const k of Object.keys(params)) s = s.replaceAll(`{${k}}`, params[k]);
  }
  return s;
}

export function nameOf(obj) {
  if (!obj) return "";
  return lang === "en" ? obj.name_en || obj.name_ru : obj.name_ru || obj.name_en;
}
